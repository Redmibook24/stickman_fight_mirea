namespace StickmanFight.Net;

/// <summary>
/// Тип команды (пакета). Занимает 1 байт в заголовке.
/// Диапазоны зарезервированы, чтобы протокол можно было расширять
/// механиками игры «Битва жердяев» без ломки уже написанного кода.
/// </summary>
public enum PacketType : byte
{
    // --- служебные (1..9) ---
    Connect    = 1,  // клиент -> сервер: рукопожатие, представление игрока
    ConnectAck = 2,  // сервер -> клиент: игрок принят, выдан id и стартовое состояние
    Disconnect = 3,  // клиент -> сервер: корректный выход
    Error      = 9,  // сервер -> клиент: пакет отвергнут (текстовая причина)

    // --- команды игрока (10..19) ---
    Movement   = 10, // клиент -> сервер: желаемое перемещение (dx, dy, dz)
    Shoot      = 11, // клиент -> сервер: выстрел (оружие + направление)

    // зарезервировано под следующие практики:
    // MeleeAttack = 12, Dash = 13, Grab = 14, Shield = 15, PickupItem = 16

    // --- ответы сервера (20..29) ---
    StateUpdate = 20, // сервер -> клиент: обновлённое состояние игрока
    ShootResult = 21, // сервер -> клиент: результат выстрела (попал/промах, урон)
}
