namespace StickmanFight.Latency.Protocol;

/// <summary>Тип пакета. Занимает 1 байт в заголовке.</summary>
public enum PacketType : byte
{
    Ping     = 1,   // клиент -> сервер: замер задержки
    Pong     = 2,   // сервер -> клиент: ответ с отметками времени сервера
    Movement = 3,   // команды из практической работы №1, здесь не используются,
    Shoot    = 4,   // но коды за ними закреплены, чтобы протокол оставался общим
}
